#!/usr/bin/env python3
"""Writes tools/otatest/vector.h for ota_test.cpp: a small ESP32 app image (one segment, with the RPOTA marker),
signed by tools/ota/sign.py with a throwaway test key (not the release key), and that key's public half. So the test
checks the firmware's verify (ota_crypto.h) against what the signing tool makes. Run again only to change it."""
import hashlib, os, struct, sys
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, "..", "ota"))
import sign  # noqa: E402

body = bytearray(os.urandom(9000))
body[100:100 + 20] = b"RPOTA:1005000:v1.5;\0"
seg = struct.pack("<II", 0x3C000000, len(body)) + body
header = bytearray(24)
header[0], header[1], header[23] = 0xE9, 1, 1
img = bytes(header) + seg
img += b"\0" * ((len(img) + 1 + 15) // 16 * 16 - len(img) - 1) + b"\xEF"
img += hashlib.sha256(img).digest()
assert sign.image_length(img) == len(img)
key = ec.generate_private_key(ec.SECP256R1())
signed, seq, version = sign.sign(img, key)
pub = key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
other = ec.generate_private_key(ec.SECP256R1()).public_key().public_bytes(
    serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
arr = lambda name, b: f"static const uint8_t {name}[{len(b)}] = {{" + ",".join(str(x) for x in b) + "};\n"
with open(os.path.join(here, "vector.h"), "w") as f:
    f.write("// Generated by tools/otatest/make_vector.py: a signed test image (a throwaway key, not the release key).\n"
            "#pragma once\n#include <stdint.h>\n" + arr("TEST_KEY", pub) + arr("OTHER_KEY", other) +
            arr("SIGNED_IMAGE", signed) + f"static const uint32_t IMAGE_LEN = {len(img)};\n")
print("wrote vector.h:", len(img), "bytes,", version, seq)
