# PlatformIO pre-build script (Xteink X4 only): the web app in site/x4 (index.html, app.js, house.wasm), gzipped
# into a header in the build folder, so the X4 serves the same files as the website from its own hotspot
# (src/apps/house/phone.cpp). Rewritten only when the files change.
import gzip
import os

Import("env")

project = env.subst("$PROJECT_DIR")
src = os.path.join(project, "site", "x4")
files = [("/", "index.html", "text/html; charset=utf-8"), ("/app.js", "app.js", "text/javascript; charset=utf-8"),
         ("/house.wasm", "house.wasm", "application/wasm")]

out = ['#pragma once', '// Generated by tools/embed_web.py from site/x4: do not edit.', '#include <stddef.h>',
       '#include <stdint.h>', 'struct WebFile { const char *path, *type; const uint8_t *data; size_t size; };']
for i, (_, name, _) in enumerate(files):
    data = gzip.compress(open(os.path.join(src, name), "rb").read(), compresslevel=9, mtime=0)
    body = ",".join(str(b) for b in data)
    out.append("static const uint8_t WEB_%d[] = {%s};" % (i, body))
out.append("static const WebFile WEB_FILES[] = {")
for i, (path, _, kind) in enumerate(files):
    out.append('  {"%s", "%s", WEB_%d, sizeof WEB_%d},' % (path, kind, i, i))
out.append("};")
text = "\n".join(out) + "\n"

folder = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(folder, exist_ok=True)
header = os.path.join(folder, "x4_web.h")
if not os.path.exists(header) or open(header).read() != text:
    with open(header, "w") as f:
        f.write(text)
env.Append(CPPPATH=[folder])
