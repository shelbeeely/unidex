#!/usr/bin/env python3
"""The catalog (things a Pet holds and clothes it wears), from catalog/items.txt (and the sprites it names), for the
firmware and the web:

  src/apps/pet/items.h      the X4's built-in items (items_logic.h's Item: id, name, 16x16 picture)
  site/x4/items.js          the same for the web app and the RoomiePet page
  site/x4/kenney.png        Kenney's 1-Bit Pack sheet (CC0), for the web app's Items page: pick any tile to add

  python3 tools/items/build.py          writes them
  python3 tools/items/build.py --check  fails if any is out of date

An item's id is the CRC-32 of its name, kind, shape, top, rows and picture, kept to 24 bits (as items_logic.h's idOf).
A Kenney tile or a 16 x 16 PNG is an ICON; a 32 x 32 PNG is a PIECE of the Pet's grid (black: ink, white: paper,
transparent: see-through), kept to the rows it uses.
"""
import json, os, re, shutil, sys, zlib
from PIL import Image

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
cat = os.path.join(root, "catalog")
SHEET = os.path.join(cat, "kenney-1-bit-pack", "sheet.png")
TILE, COLS = 16, 49  # the packed sheet: 49 tiles a row, no gaps


def ink(px, white_is_ink):
    """Ink: not transparent (and, in our own sprites, not white; Kenney's are white on transparent)."""
    r, g, b, a = px
    return a > 127 and (white_is_ink or (r + g + b) < 600)


def bits_of(img, white_is_ink=False):
    out = bytearray(32)
    for y in range(16):
        for x in range(16):
            if ink(img.getpixel((x, y)), white_is_ink):
                out[y * 2 + x // 8] |= 0x80 >> (x % 8)
    return bytes(out)


def sprite(spec, sheet):
    if spec.startswith("kenney:"):
        n = int(spec[7:])
        c, r = n % COLS, n // COLS
        return sheet.crop((c * TILE, r * TILE, c * TILE + TILE, r * TILE + TILE))
    img = Image.open(os.path.join(cat, "sprites", spec)).convert("RGBA")
    assert img.size == (16, 16), f"{spec}: {img.size}, not 16 x 16"
    return img


KINDS = ["hand", "hat", "accessory", "hair", "outfit"]
ICON, PIECE = 0, 1


def item_id(name, kind, shape, top, rows, data):
    c = zlib.crc32(name.encode())
    c = zlib.crc32(bytes([kind, shape, top, rows]), c)
    c = zlib.crc32(data, c) & 0xFFFFFF
    return c or 1


def piece_of(img, spec):
    """A 32 x 32 PNG as items_logic.h's PIECE: (top, rows, data), 2 bits a pixel (0 clear, 1 ink, 2 paper)."""
    assert img.size == (32, 32), f"{spec}: {img.size}, not 32 x 32"
    code = lambda px: 0 if px[3] <= 127 else 1 if sum(px[:3]) < 384 else 2
    grid = [[code(img.getpixel((x, y))) for x in range(32)] for y in range(32)]
    used = [y for y in range(32) if any(grid[y])]
    assert used, f"{spec} is blank"
    top, rows = used[0], used[-1] - used[0] + 1
    assert rows <= 27, f"{spec}: {rows} rows; a piece can use 27 at most"
    data = bytearray(rows * 8)
    for y in range(rows):
        for x in range(32):
            data[y * 8 + x // 4] |= grid[top + y][x] << (6 - 2 * (x % 4))
    return top, rows, bytes(data)


sheet = Image.open(SHEET).convert("RGBA")
items = []
for n, line in enumerate(open(os.path.join(cat, "items.txt")), 1):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    parts = [p.strip() for p in line.split(",")]
    name, spec, kind = parts[0], parts[1], parts[2] if len(parts) > 2 else "hand"
    assert 1 <= len(name) <= 12 and all(32 <= ord(ch) < 127 for ch in name), f"line {n}: name {name!r}"
    assert kind in KINDS, f"line {n}: kind {kind!r} (one of {', '.join(KINDS)})"
    k = KINDS.index(kind)
    img = sprite(spec, sheet) if spec.startswith("kenney:") else Image.open(os.path.join(cat, "sprites", spec)).convert("RGBA")
    if img.size == (32, 32):
        assert kind != "hand", f"line {n}: a 32 x 32 piece is worn, not held"
        top, rows, data = piece_of(img, spec)
        shape = PIECE
    else:
        assert kind in ("hand", "hat", "accessory"), f"line {n}: {kind} needs a 32 x 32 piece"
        data, shape, top, rows = bits_of(img if spec.startswith("kenney:") else sprite(spec, sheet), spec.startswith("kenney:")), ICON, 0, 16
        assert any(data), f"line {n}: {spec} is blank"
    items.append({"id": item_id(name, k, shape, top, rows, data), "name": name, "kind": k, "shape": shape, "top": top,
                  "rows": rows, "data": data, "from": spec})
ids = [i["id"] for i in items]
assert len(set(ids)) == len(ids), "two items have the same id"
names = [i["name"] for i in items]
assert len(set(names)) == len(names), "two items have the same name"

h = ["#pragma once",
     "// Generated by tools/items/build.py from catalog/items.txt: don't edit, change that and run the script.",
     "// The catalog the firmware brings: things to hold and clothes (items_logic.h). Sprites from Kenney's 1-Bit Pack (CC0,",
     "// www.kenney.nl) and catalog/sprites.",
     '#include "items_logic.h"', "",
     "static const items::Item BUILTIN_ITEMS[] = {"]
for i in items:
    h.append('  {0x%06X, "%s", %d, %d, %d, %d, {%s}},  // %s %s' % (
        i["id"], i["name"], i["kind"], i["shape"], i["top"], i["rows"], ", ".join("0x%02X" % b for b in i["data"]),
        KINDS[i["kind"]], i["from"]))
h += ["};", "static const int BUILTIN_ITEM_COUNT = sizeof BUILTIN_ITEMS / sizeof BUILTIN_ITEMS[0];", ""]
header = "\n".join(h)

js = ("// Generated by tools/items/build.py from catalog/items.txt: don't edit, change that and run the script.\n"
      "// The catalog the X4's firmware brings (items_logic.h): id (24 bits), name, kind (0 hand, 1 hat, 2 accessory,\n"
      "// 3 hair, 4 outfit), shape (0 icon: 16x16, 1 bit a pixel; 1 piece: rows top.. of the Pet's grid, 2 bits a pixel),\n"
      "// top, rows, picture (hex). Sprites from Kenney's 1-Bit Pack (CC0) and catalog/sprites.\n"
      "export const ITEMS = " + json.dumps([{"id": i["id"], "name": i["name"], "kind": i["kind"], "shape": i["shape"],
                                           "top": i["top"], "rows": i["rows"], "data": i["data"].hex()} for i in items],
                                          separators=(",", ":")) + ";\n"
      "export const KINDS = " + json.dumps(KINDS) + ";\n"
      "export const KENNEY = { sheet: 'kenney.png', tile: 16, cols: 49, count: %d };\n" % (
          (sheet.size[0] // TILE) * (sheet.size[1] // TILE)))

outs = [(os.path.join(root, "src/apps/pet/items.h"), header), (os.path.join(root, "site/x4/items.js"), js)]
kenney_web = os.path.join(root, "site/x4/kenney.png")
if "--check" in sys.argv:
    stale = [os.path.relpath(p, root) for p, t in outs if not os.path.exists(p) or open(p).read() != t]
    if not os.path.exists(kenney_web) or open(kenney_web, "rb").read() != open(SHEET, "rb").read():
        stale.append("site/x4/kenney.png")
    if stale:
        sys.exit(f"{', '.join(stale)} out of date: run python3 tools/items/build.py")
    print(f"items up to date ({len(items)})")
else:
    for p, t in outs:
        open(p, "w").write(t)
    shutil.copyfile(SHEET, kenney_web)
    print(f"wrote src/apps/pet/items.h, site/x4/items.js and site/x4/kenney.png: {len(items)} items")
